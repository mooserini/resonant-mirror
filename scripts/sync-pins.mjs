// sync-pins.mjs — regenerate the project showcase from Moose's GitHub pins.
//
// The Projects section mirrors the repositories pinned on
// https://github.com/mooserini — pins are the single source of truth.
// Moose maintains the pins, the descriptions, the topics and the repo
// homepages on GitHub; this script pulls them through the local `gh`
// session (GraphQL is the only API that exposes pins, and it requires
// auth — gh already holds it) and rewrites src/data/pinnedProjects.ts.
//
// Run it from a terminal where `gh` is signed in:   npm run sync-pins
// Then commit the regenerated file; the next deploy picks it up.
//
// Field derivations (mechanical, no editorializing):
//   title    = repo name, hyphens as spaces
//   codename = repo name, uppercased
//   summary/description = the repo description, verbatim (trimmed)
//   year     = the repo's creation year
//   tags     = repo topics (first 6, GitHub order); if none, the language
//   link     = repo homepage, unless it points at this site itself
//   featured = true for every pin — pinning IS the featuring
// Category is the one field GitHub cannot supply (it drives the section's
// filter tabs), so it lives in the small map below. A newly pinned repo
// with no entry stops the sync loudly instead of inventing one.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const CATEGORY_BY_REPO = {
  "The-Resonant-Mirror": "web",
  "hermes-config-guardian": "security",
  "whole": "ai",
  "vesper-real-weather-lab": "retro",
  "IMAPIIe-Now": "systems",
  "hermes-openwhispr": "ai",
};

const SELF_ORIGINS = ["https://www.getadongle.com", "https://getadongle.com"];

const QUERY = `{
  user(login: "mooserini") {
    pinnedItems(first: 6, types: REPOSITORY) {
      nodes {
        ... on Repository {
          name
          url
          description
          homepageUrl
          createdAt
          primaryLanguage { name }
          repositoryTopics(first: 20) { nodes { topic { name } } }
        }
      }
    }
  }
}`;

const raw = execFileSync("gh", ["api", "graphql", "-f", `query=${QUERY}`], {
  encoding: "utf8",
});
const nodes = JSON.parse(raw).data.user.pinnedItems.nodes.filter(Boolean);
if (nodes.length === 0) throw new Error("No pinned repositories returned.");

const projects = nodes.map((r) => {
  const category = CATEGORY_BY_REPO[r.name];
  if (!category) {
    throw new Error(
      `Pinned repo "${r.name}" has no category in scripts/sync-pins.mjs — add one and re-run.`
    );
  }
  const topics = (r.repositoryTopics?.nodes ?? []).map((n) => n.topic.name);
  const tags = topics.length > 0 ? topics.slice(0, 6) : r.primaryLanguage ? [r.primaryLanguage.name] : [];
  const homepage = (r.homepageUrl ?? "").trim();
  const link = homepage && !SELF_ORIGINS.some((o) => homepage === o || homepage.startsWith(o + "/")) ? homepage : undefined;
  const description = (r.description ?? "").trim();
  return {
    id: r.name.toLowerCase(),
    title: r.name.replace(/-/g, " "),
    codename: r.name.toUpperCase(),
    category,
    summary: description,
    description,
    year: String(r.createdAt).slice(0, 4),
    tags,
    ...(link ? { link } : {}),
    repoUrl: r.url,
    sourceKind: "repository",
    featured: true,
  };
});

const out = `// GENERATED by scripts/sync-pins.mjs — do not hand-edit.
// Source: github.com/mooserini pinned repositories (GraphQL), in pin order.
// Regenerate with: npm run sync-pins
import type { Project } from "../types";

export const PINNED_PROJECTS: Project[] = ${JSON.stringify(projects, null, 2)};
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "data", "pinnedProjects.ts");
writeFileSync(dest, out);
console.log(`Wrote ${projects.length} pinned projects to src/data/pinnedProjects.ts`);
